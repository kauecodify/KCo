@dataclass
class MonitoringConfig:
    """Configuration for monitoring system"""
    update_interval: float = 1.0
    max_history: int = 1000
    enable_telemetry: bool = True
    enable_geofencing: bool = True
    enable_anomaly_detection: bool = True
    alert_thresholds: Dict[str, float] = field(default_factory=dict)


@dataclass
class EntityMonitoringData:
    """Monitoring data for a single entity"""
    entity_id: str
    entity_type: str
    last_update: datetime = field(default_factory=datetime.utcnow)
    position_history: List[Dict[str, float]] = field(default_factory=list)
    speed_history: List[float] = field(default_factory=list)
    altitude_history: List[float] = field(default_factory=list)
    heading_history: List[float] = field(default_factory=list)
    status_history: List[str] = field(default_factory=list)
    alerts: List[Dict[str, Any]] = field(default_factory=list)
    
    def add_position(self, lat: float, lng: float, alt: float = 0.0) -> None:
        """Add a position to history"""
        self.position_history.append({
            "timestamp": datetime.utcnow().isoformat(),
            "latitude": lat,
            "longitude": lng,
            "altitude": alt
        })
        if len(self.position_history) > 100:
            self.position_history = self.position_history[-100:]
    
    def add_speed(self, speed: float) -> None:
        """Add speed to history"""
        self.speed_history.append(speed)
        if len(self.speed_history) > 100:
            self.speed_history = self.speed_history[-100:]
    
    def add_altitude(self, altitude: float) -> None:
        """Add altitude to history"""
        self.altitude_history.append(altitude)
        if len(self.altitude_history) > 100:
            self.altitude_history = self.altitude_history[-100:]
    
    def add_heading(self, heading: float) -> None:
        """Add heading to history"""
        self.heading_history.append(heading)
        if len(self.heading_history) > 100:
            self.heading_history = self.heading_history[-100:]
    
    def add_status(self, status: str) -> None:
        """Add status to history"""
        self.status_history.append(status)
        if len(self.status_history) > 100:
            self.status_history = self.status_history[-100:]
    
    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary"""
        return {
            "entity_id": self.entity_id,
            "entity_type": self.entity_type,
            "last_update": self.last_update.isoformat(),
            "position_history": self.position_history,
            "speed_history": self.speed_history,
            "altitude_history": self.altitude_history,
            "heading_history": self.heading_history,
            "status_history": self.status_history,
            "alerts": self.alerts
        }


@dataclass
class MonitoringAlert:
    """Alert generated by monitoring system"""
    alert_id: str
    entity_id: str
    entity_type: str
    alert_type: str
    severity: str
    message: str
    value: float
    threshold: float
    timestamp: datetime = field(default_factory=datetime.utcnow)
    metadata: Dict[str, Any] = field(default_factory=dict)
    
    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary"""
        return {
            "alert_id": self.alert_id,
            "entity_id": self.entity_id,
            "entity_type": self.entity_type,
            "alert_type": self.alert_type,
            "severity": self.severity,
            "message": self.message,
            "value": self.value,
            "threshold": self.threshold,
            "timestamp": self.timestamp.isoformat(),
            "metadata": self.metadata
        }


class MonitoringSystem:
    """
    Real-time monitoring system for helicopters and vehicles
    
    Features:
    - Real-time telemetry monitoring
    - Threshold-based alerts
    - Historical data tracking
    - Performance metrics
    - Custom monitoring rules
    """
    
    def __init__(self, config: Optional[MonitoringConfig] = None):
        """
        Initialize monitoring system
        
        Args:
            config: Monitoring configuration
        """
        self.config = config or MonitoringConfig()
        self.is_running = False
        self.monitoring_data: Dict[str, EntityMonitoringData] = {}
        self.alerts: Dict[str, MonitoringAlert] = {}
        self.callbacks: List[Callable] = []
        self.custom_rules: Dict[str, Callable] = {}
        
        # Default alert thresholds
        self.default_thresholds = {
            "max_speed": {
                "helicopter": 250.0,  # km/h
                "vehicle": 150.0
            },
            "min_altitude": {
                "helicopter": 10.0,  # meters
                "vehicle": 0.0
            },
            "max_altitude": {
                "helicopter": 3000.0,  # meters
                "vehicle": 100.0
            },
            "rapid_descent": {
                "helicopter": -10.0,  # m/s
                "vehicle": -5.0
            },
            "rapid_ascent": {
                "helicopter": 10.0,  # m/s
                "vehicle": 5.0
            }
        }
        
        logger.info("Monitoring System initialized")
    
    async def start(self) -> None:
        """Start monitoring"""
        if self.is_running:
            logger.warning("Monitoring System is already running")
            return
        
        self.is_running = True
        logger.info("Monitoring System started")
        
        while self.is_running:
            try:
                await self._monitor_all_entities()
                await asyncio.sleep(self.config.update_interval)
            except Exception as e:
                logger.error(f"Error in monitoring loop: {e}")
    
    async def stop(self) -> None:
        """Stop monitoring"""
        self.is_running = False
        logger.info("Monitoring System stopped")
    
    async def _monitor_all_entities(self) -> None:
        """Monitor all tracked entities"""
        # Monitor helicopters
        for helicopter in fleet_manager.helicopters.values():
            await self._monitor_entity(helicopter.helicopter_id, "helicopter", helicopter)
        
        # Monitor vehicles
        for vehicle in fleet_manager.vehicles.values():
            await self._monitor_entity(vehicle.vehicle_id, "vehicle", vehicle)
        
        # Check custom rules
        await self._check_custom_rules()
    
    async def _monitor_entity(self, entity_id: str, entity_type: str, entity: Any) -> None:
        """Monitor a single entity"""
        # Initialize monitoring data if not exists
        if entity_id not in self.monitoring_data:
            self.monitoring_data[entity_id] = EntityMonitoringData(
                entity_id=entity_id,
                entity_type=entity_type
            )
        
        monitor_data = self.monitoring_data[entity_id]
        
        # Get current location
        if entity_type == "helicopter":
            location = entity.location
            speed = location.speed
            altitude = location.altitude
            heading = location.heading
            status = entity.status.value
        else:  # vehicle
            location = entity.location
            speed = location.speed
            altitude = location.altitude
            heading = location.heading
            status = entity.status.value
        
        # Update monitoring data
        monitor_data.add_position(location.latitude, location.longitude, altitude)
        monitor_data.add_speed(speed)
        monitor_data.add_altitude(altitude)
        monitor_data.add_heading(heading)
        monitor_data.add_status(status)
        monitor_data.last_update = datetime.utcnow()
        
        # Check thresholds
        await self._check_thresholds(entity_id, entity_type, speed, altitude, heading, status)
    
    async def _check_thresholds(self, entity_id: str, entity_type: str,
                               speed: float, altitude: float, heading: float, 
                               status: str) -> None:
        """Check if any thresholds are exceeded"""
        # Get thresholds for this entity type
        thresholds = self.default_thresholds
        if entity_type in self.config.alert_thresholds:
            thresholds = self.config.alert_thresholds[entity_type]
        
        # Check max speed
        max_speed = thresholds.get("max_speed", {}).get(entity_type, 999.0)
        if speed > max_speed:
            await self._create_alert(
                entity_id=entity_id,
                entity_type=entity_type,
                alert_type="speed_exceeded",
                severity="warning",
                message=f"Speed limit exceeded: {speed:.1f} km/h > {max_speed:.1f} km/h",
                value=speed,
                threshold=max_speed
            )
        
        # Check min altitude (for helicopters)
        if entity_type == "helicopter":
            min_alt = thresholds.get("min_altitude", {}).get("helicopter", 0.0)
            if altitude < min_alt and altitude > 0:
                await self._create_alert(
                    entity_id=entity_id,
                    entity_type=entity_type,
                    alert_type="low_altitude",
                    severity="warning",
                    message=f"Low altitude: {altitude:.1f} m < {min_alt:.1f} m",
                    value=altitude,
                    threshold=min_alt
                )
            
            # Check max altitude
            max_alt = thresholds.get("max_altitude", {}).get("helicopter", 9999.0)
            if altitude > max_alt:
                await self._create_alert(
                    entity_id=entity_id,
                    entity_type=entity_type,
                    alert_type="high_altitude",
                    severity="warning",
                    message=f"High altitude: {altitude:.1f} m > {max_alt:.1f} m",
                    value=altitude,
                    threshold=max_alt
                )
        
        # Check for emergency status
        if status == "emergency":
            await self._create_alert(
                entity_id=entity_id,
                entity_type=entity_type,
                alert_type="emergency",
                severity="critical",
                message=f"{entity_type.capitalize()} {entity_id} in EMERGENCY status",
                value=0,
                threshold=0
            )
        
        # Check for geofence violations
        if self.config.enable_geofencing:
            await self._check_geofences(entity_id, entity_type)
    
